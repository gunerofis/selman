function matchesLineItem(item, line, q) {
	const raw = foldTr(q.trim());
	if (!raw) return true;
	const hay = foldTr([
		line.kicker,
		line.title,
		item.name,
		item.code ?? "",
		item.kind ?? "",
		...item.tags ?? [],
		item.note ?? ""
	].join(" "));
	return raw.split(/\s+/).filter(Boolean).every((w) => hay.includes(w) || fuzzyIncludes(hay, w));
}
